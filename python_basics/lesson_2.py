# Numbers
a = 10
b = 3

print(a + b)   # Addition
print(a - b)   # Subtraction  
print(a * b)   # Multiplication
print(a / b)   # Division
print(a // b)  # Integer division (no decimal)
print(a % b)   # Modulus (get remainder)
print(a ** 2)  # Power (10 to the power 2)

# Strings
first = "King"
last = "STPS"
full = first + " " + last
print(full)
print(full.upper())
print(full.lower())

# Lists - ordered collection
skills = ["Python", "VS Code", "AI"]
skills.append("Machine Learning")
print(skills)
print(len(skills))        # Length
print(skills[0])          # First item

things_to_learn = ["Automation", "Machine Learning", "Data Analysis", "Terminal"]
print(things_to_learn)
print(len(things_to_learn))